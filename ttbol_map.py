"""ttbol_map.py — نگاشتِ محصولِ competitor-shop.example → فرمتِ اتریبیوتِ سایتِ ما (نسخهٔ اولیه؛ اپراتور دقیقش می‌کند).

اتریبیوت‌های ttbol ساختارمندند ولی نام/ولیوهاشان با ما فرق دارد. آنچه واضح است نگاشت می‌شود؛
بقیه «⟨بدون‌نگاشت⟩» می‌ماند تا اپراتور قانون بدهد (مثلِ irantimer). واژگانِ هدف = همان سایتِ خودمان.
"""
from __future__ import annotations

import re
from collections import OrderedDict

import irantimer_map as im  # بازاستفاده: OUT_ATTRS، norm_color، جداکنندهٔ « | »

_SEP = " | "
_UNMAP = "⟨بدون‌نگاشت⟩"


def _first(vals):
    return (vals[0] if vals else "").strip()


# ---------- نگاشت‌های seed (ttbol → واژگانِ سایتِ ما) ----------
_GENDER = {"آقایان": "مردانه", "مردانه": "مردانه", "خانم ها": "زنانه", "بانوان": "زنانه", "زنانه": "زنانه",
           "بچگانه": "بچه گانه", "بچه گانه": "بچه گانه", "ست": "ست", "زنانه و مردانه": "زنانه - مردانه"}
_SHAPE = {"گرد": "گرد", "چهار گوش": "مربع", "مربع": "مربع", "مستطیل": "مستطیل", "بیضی": "بیضی",
          "چند ضلعی": "سایر اشکال", "سایر": "سایر اشکال"}
_GLASS = {"معدنی مقاوم در برابر خش": "مینرال هارد (مقاوم در برابر خش)", "معدنی": "مینرال", "مینرال": "مینرال",
          "کریستال مالی": "سافایر (یاقوت کبود)", "سافایر": "سافایر (یاقوت کبود)", "طلق": "طلق", "رزین": "رزین"}
_LOCK = {"ضامن دار (کلیپسی)": "کلیپسی", "کلیپسی": "کلیپسی", "کمربندی": "سگکی", "سگکی": "سگکی",
         "پروانه ای": "پروانه ای", "دستبندی": "دستبندی"}
# مقاومت در برابر آب: ATM → عبارتِ سایت
_WATER = {"3ATM": "مناسب برای شستشوی دست (30متر)", "5ATM": "مناسب برای استحمام (50متر)",
          "10ATM": "مناسب برای ورزش های آبی و شنا (100متر)", "20ATM": "مناسب برای غواصی (200متر)",
          "30ATM": "مناسب برای غواصی (300متر)"}
_MATERIAL = {"استیل": "استیل", "استیل ضد زنگ": "استیل", "چرم": "چرم", "چرمی": "چرم", "سیلیکون": "سیلیکون",
             "رابر": "رابر", "پلاستیک": "پلاستیک فشرده", "رزین": "رزین", "تیتانیوم": "تیتانیوم"}
# امکانات: نشانگر/کرنومتر/شب‌تاب/تاکی‌متر → ترمِ سایت
_FEATURE = [("کرنومتر", "دارد", "کورنوگراف"), ("عقربه های شب تاب", "دارد", "عقربه شب نما"),
            ("سرعت سنج (تاکی متر)", "دارد", "تاچیمتر")]


def _map(d, val):
    return d.get((val or "").strip(), "")


def map_product(p: dict, brand: str) -> "OrderedDict":
    a = p.get("attrs", {})

    def g(name):
        return _first(a.get(name, []))

    row = OrderedDict()
    row["نام برند"] = brand
    row["رفرانس"] = p.get("ref", "")
    row["مناسب برای"] = _map(_GENDER, g("مناسب برای"))
    row["استایل"] = ""  # «سبک» → استایل: نگاشتِ اپراتور (روزمره/رسمی/اسپرت…)
    row["طرح صفحه"] = ""  # ttbol ندارد → اپراتور/خالی
    row["رنگ صفحه"] = im.norm_color(g("رنگ صفحه"))
    row["شکل قاب"] = _map(_SHAPE, g("فرم صفحه"))
    row["میزان ضدآبی"] = _map(_WATER, g("مقاومت در برابر آب"))
    row["جنس بکارگرفته"] = _map(_MATERIAL, g("جنس بدنه")) or g("جنس بدنه")
    # امکانات دیگر: نشانگرها + فلگ‌های دارد
    feats = []
    for ind in a.get("نشانگرها", []):
        pass  # نشانگرها (تاریخ/روز/…) نگاشتِ اپراتور لازم دارد؛ فعلاً در امکانات نمی‌آید
    for attr, yes, term in _FEATURE:
        if yes in a.get(attr, []) and term not in feats:
            feats.append(term)
    row["امکانات دیگر"] = _SEP.join(feats)
    row["رنگ بند"] = im.norm_color(g("رنگ بند"))
    row["رنگ قاب"] = ""  # ttbol ندارد
    # نوع موتور: ترکیبِ تکنولوژی + منبع — نگاشتِ اپراتور لازم است
    tech = g("تکنولوژی ساخت")
    row["نوع موتور"] = _UNMAP + f"(تکنولوژی={tech}|موتور={g('نوع موتور')}|انرژی={g('منبع انرژی')})" if tech else ""
    row["نوع شیشه"] = _map(_GLASS, g("جنس شیشه")) or (_UNMAP + g("جنس شیشه") if g("جنس شیشه") else "")
    row["طرح بند"] = _UNMAP + g("جنس بند") if g("جنس بند") else ""  # «جنس بند» ttbol ↔ طرح بندِ ما؟ اپراتور
    row["نوع قفل"] = _map(_LOCK, g("نوع قفل بند")) or (_UNMAP + g("نوع قفل بند") if g("نوع قفل بند") else "")
    row["تقویم و نوع آن"] = ""  # از «نشانگرها» استخراج شود؟ اپراتور
    row["نگین"] = ""
    row["گارانتی"] = ""            # «گارانتی» ttbol شاملِ نامِ برند است → اپراتور
    row["گارانتی کننده در ایران"] = ""
    row["موارد گارانتی"] = "کارکرد موتور | مقاومت در برابر آب"  # ثابت (قانونِ اپراتور)
    row["اصالت برند"] = ""
    row["کشور سازنده"] = ""
    row["سایز قاب"] = ""
    row["ارتفاع قاب"] = ""
    row["عرض بند"] = ""
    row["وزن ساعت"] = ""
    return row
